_start:
    mov  w19, #FAKE_ROUNDS          // repetições do roteiro

next_round:
    adrp x20, stream
    add  x20, x20, :lo12:stream

frame_loop:
    ldrb w21, [x20], #1             // tamanho do quadro; x20 -> primeiro byte
    cbz  w21, round_done

    mov  x0, #STDOUT
    mov  x1, x20
    mov  x2, x21
