    svc  #0
    add  x20, x20, x21

    adrp x0, delay
    add  x0, x0, :lo12:delay
    mov  x1, #0
    mov  x8, #SYS_NANOSLEEP
    svc  #0
    b    frame_loop

round_done:
    subs w19, w19, #1
    bne next_round

    mov  x0, #0
    mov  x8, #SYS_EXIT
    svc  #0
